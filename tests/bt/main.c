static void test_h4(void) {
	BtH4 h;
	uint8_t frame[16];
	uint8_t kind = 0, out[16];
	uint16_t olen = 0;
	int n;
	uint8_t cmd[3] = {0x03, 0x0c, 0x00};
	bt_h4_reset(&h);
	n = bt_h4_wrap(H4_CMD, cmd, 3, frame, sizeof frame);
	expect("h4-wrap", n == 4 && frame[0] == H4_CMD);
	expect("h4-feed", bt_h4_feed(&h, frame, (size_t)n, &kind, out, &olen, sizeof out) == 1 &&
						  kind == H4_CMD && olen == 3 && out[0] == 0x03);

	/* frame larger than the caller's buffer must be dropped whole with the
	 * stream left in sync -- copying it overran out[] and smashed the
	 * bthost kernel stack on boot-time scans (ACL len 0x0345) */
	{
		uint8_t evil[5] = {H4_ACL, 0x01, 0x20, 0x45, 0x03};
		uint8_t pad[64];
		int left;
		memset(pad, 0xa5, sizeof pad);
		bt_h4_reset(&h);
		kind = 0;
		olen = 0;
		expect("h4-oversize-hdr",
			   bt_h4_feed(&h, evil, sizeof evil, &kind, out, &olen, sizeof out) == 0);
		/* evil[] already delivered the kind + 4-byte header; the frame
		 * wants 837 payload bytes before it completes and gets dropped */
		for (left = 837; left > 0; left -= (int)sizeof pad)
			bt_h4_feed(&h, pad, left > (int)sizeof pad ? sizeof pad : (size_t)left, &kind,
					   out, &olen, sizeof out);
		expect("h4-oversize-dropped", olen == 0);
		n = bt_h4_wrap(H4_CMD, cmd, 3, frame, sizeof frame);
		expect("h4-resync",
			   bt_h4_feed(&h, frame, (size_t)n, &kind, out, &olen, sizeof out) == 1 &&
				   kind == H4_CMD && olen == 3);
	}
}

static void test_parse(void) {
	const uint8_t ad[] = {0x02, 0x01, 0x06, 0x05, 0x09, 'T', 'e', 's', 't'};
	char name[16];
	uint8_t cmd[8];
	uint8_t req[3];
	uint8_t rsp[] = {0x0b, 'A', 'b'};
	uint8_t val[8];
	BtBondRec rec;
	expect("ad-name", bt_ad_name(ad, (int)sizeof ad, name, 16) == 4 && strcmp(name, "Test") == 0);
	expect("hci-reset", bt_hci_cmd(cmd, 0x0C03, NULL, 0) == 3 && cmd[0] == 0x03 && cmd[1] == 0x0c && cmd[2] == 0);
	expect("att-read", bt_att_read_req(req, 0x0003) == 3 && req[0] == 0x0a && req[1] == 0x03);
	expect("att-rsp", bt_att_read_rsp(rsp, 3, val, 8) == 2 && val[0] == 'A' && val[1] == 'b');
	memset(&rec, 0, sizeof rec);
	rec.magic = BT_BOND_MAGIC;
	rec.addr[0] = 1;
	expect("bond", rec.magic == BT_BOND_MAGIC && rec.addr[0] == 1);
}

static void test_lc3(void) {
	int16_t pcm[LC3_SAMPLES];
	int16_t back[LC3_SAMPLES];
	uint8_t frame[LC3_BYTES];
	uint8_t again[LC3_BYTES];
	int i;
	int64_t sig = 0, err = 0;
	for (i = 0; i < LC3_SAMPLES; i++)
		pcm[i] = (int16_t)((i * 50) % 2000 - 1000);
	expect("lc3-len", bt_lc3_encode(pcm, frame) == LC3_BYTES && frame[0] == 0x16);
	bt_lc3_encode(pcm, again);
	expect("lc3-stable", memcmp(frame, again, LC3_BYTES) == 0);
	expect("lc3-dec", bt_lc3_decode(frame, back) == LC3_SAMPLES);
	for (i = 0; i < LC3_SAMPLES; i++) {
		int32_t d = (int32_t)pcm[i] - back[i];
		sig += (int64_t)pcm[i] * pcm[i];
		err += (int64_t)d * d;
	}
	expect("lc3-energy", sig > 0 && err * 4 < sig * 3);
}

